    private static final String TAG = "CarPlayHook";
    /* Auto-generated by build_java.sh - do not edit manually */
    private static final String BUILD_ID = "2026-10-11-allemon-1289981-lifecycle-review";

    /* State */
    private static volatile boolean active = false;
    private static volatile boolean registered = false;
    private static volatile boolean retrying = false;
    private static volatile boolean carplayRunning = false;

    private static volatile IFrameworkAccess frameworkAccess = null;

    private static Object savedContext = null;
    private static DeviceStateHandler listenerProxy = null;

    /* Modules (cover art handled by TerminalModeBapCombi$EventListener) */
    private static volatile RouteGuidance routeGuidance = null;
    private static Thread rgiRuntimeMonitor;
    private static Thread retryThread;
    private static int activationGeneration;
    private static IServiceManager naviServiceManager;
    private static ServiceReference naviServiceReference;
    private static Object boundNaviService;
    private static long lastServiceProbe;

